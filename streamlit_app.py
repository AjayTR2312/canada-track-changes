"""
Streamlit Frontend for PXML Document Processor Pipeline.
Connects to FastAPI backend. Downloads via S3 presigned URLs.
Each user session is isolated via st.session_state.
"""
import os
from dotenv import load_dotenv
load_dotenv()
import streamlit as st
import requests
import time

API_URL = os.getenv("API_URL", "http://localhost:8000")

st.set_page_config(page_title="PXML Document Processor", page_icon="📄", layout="wide")

# ─── Custom CSS ───
st.markdown("""
<style>
    .status-banner { border-radius: 8px; padding: 1rem 1.2rem; margin: 1rem 0; border-left: 4px solid #2E7D32; background: #f0f0f0; }
    .status-banner-running { border-left: 4px solid #F57C00; background: #f5f5f5; }
    .status-banner-failed { border-left: 4px solid #C62828; background: #f5f5f5; }
    footer { visibility: hidden; }
</style>
""", unsafe_allow_html=True)

# ─── Header ───
st.title("📄 PXML Document Processor")
st.caption("Automated XML revision pipeline")

# ─── Sidebar ───
with st.sidebar:
    st.markdown("### ⚙️ Configuration")
    product_type = st.selectbox("Product Type", ["looseleaf", "pamphlet"], index=0)
    st.markdown("---")
    st.markdown("### 📋 Pipeline Steps")
    steps = [
        "Track Changes Extraction", "Section Deletion", "Section Number Replacement",
        "Section Insertion & Edge Cases", "Paragraph-Level Inline Changes",
        "Newline Paragraph Insertions", "New Footnote Insertions",
        "Failed Revisions Report", "Retry Failed Deletions", "Post Processing",
        "Validation Report",
    ]
    step_placeholder = st.empty()
    with step_placeholder.container():
        for i, s in enumerate(steps, 1):
            st.markdown(f"<span class='step-pending'>○ {i}. {s}</span>", unsafe_allow_html=True)
    st.markdown("---")
    st.markdown("### 🏗️ Infrastructure")
    st.markdown("<small>• ExecutorPool: 6 workers<br>• Storage: Disk<br>• Deploy: AVD</small>", unsafe_allow_html=True)
    st.markdown("---")
    st.markdown("<small style='color:#888;'>v3.0 • S3 + ExecutorPool</small>", unsafe_allow_html=True)

# ─── Main Content ───
tab1, = st.tabs(["📁 Single Document"])

with tab1:
    col1, col2 = st.columns(2, gap="large")
    with col1:
        docx_file = st.file_uploader("📝 DOCX (revision copy)", type=["docx", "doc"], key="single_docx")
    with col2:
        pxml_file = st.file_uploader("📋 PXML (source XML)", type=["pxml"], key="single_pxml")

    st.markdown("")
    images_zip = st.file_uploader(
        "🖼️ Images ZIP (generated by the Image Conversion tool)",
        type=["zip"], key="single_images_zip",
        help="Upload the ZIP folder generated by the Image Conversion EXE."
    )

    st.markdown("")
    col_btn, _ = st.columns([1, 3])
    with col_btn:
        start_clicked = st.button(
            "🚀 Start Processing", type="primary",
            disabled=(not docx_file or not pxml_file or not images_zip), use_container_width=True
        )

    if start_clicked:
        with st.spinner("Uploading files to server & S3..."):
            files = {
                "docx_file": (docx_file.name, docx_file.getvalue(), "application/octet-stream"),
                "pxml_file": (pxml_file.name, pxml_file.getvalue(), "application/octet-stream"),
                "images_zip": (images_zip.name, images_zip.getvalue(), "application/zip"),
            }
            data = {"product_type": product_type}
            resp = requests.post(f"{API_URL}/api/process", files=files, data=data)

        if resp.status_code == 200:
            job_id = resp.json()["job_id"]
            st.session_state["current_job"] = job_id
        else:
            st.error(f"❌ Upload failed: {resp.text}")

    # ─── Status Polling ───
    if "current_job" in st.session_state:
        job_id = st.session_state["current_job"]
        st.markdown(f"<small>Job ID: <code>{job_id}</code></small>", unsafe_allow_html=True)

        status = None
        try:
            resp = requests.get(f"{API_URL}/api/status/{job_id}", timeout=15)
            if resp.status_code == 200:
                status = resp.json()
        except (requests.ConnectionError, requests.Timeout):
            st.warning("⚠️ API server is busy or unreachable. Retrying...")
            time.sleep(3)
            st.rerun()

        if status:
            progress_bar = st.progress(status["progress_pct"] / 100)

            if status["status"] == "running":
                st.markdown(
                    f"<div class='status-banner status-banner-running'>"
                    f"⏳ <strong>Processing</strong> — Step {status['current_step']}/11: {status['current_step_name']}"
                    f"</div>", unsafe_allow_html=True
                )
                with step_placeholder.container():
                    for i, s in enumerate(steps, 1):
                        if i < status["current_step"]:
                            st.markdown(f"<span class='step-done'>✓ {i}. {s}</span>", unsafe_allow_html=True)
                        elif i == status["current_step"]:
                            st.markdown(f"<span class='step-active'>▶ {i}. {s}</span>", unsafe_allow_html=True)
                        else:
                            st.markdown(f"<span class='step-pending'>○ {i}. {s}</span>", unsafe_allow_html=True)

                try:
                    log_resp = requests.get(f"{API_URL}/api/log/{job_id}")
                    if log_resp.status_code == 200:
                        log_text = log_resp.json().get("log", "")
                        with st.expander("📜 Live Log Output", expanded=False):
                            st.code(log_text[-5000:], language="text")
                except:
                    pass

                time.sleep(3)
                st.rerun()

            elif status["status"] == "completed":
                # ─── Auto-run validation as Step 11 ───
                if st.session_state.get("validation_ready") not in (True, "failed"):
                    # Show step 11 as active
                    with step_placeholder.container():
                        for i, s in enumerate(steps, 1):
                            if i <= 10:
                                st.markdown(f"<span class='step-done'>✓ {i}. {s}</span>", unsafe_allow_html=True)
                            else:
                                st.markdown(f"<span class='step-active'>▶ {i}. {s}</span>", unsafe_allow_html=True)

                    st.markdown(
                        "<div class='status-banner status-banner-running'>"
                        "⏳ <strong>Running Validation</strong> — Step 11/11: Validation Report"
                        "</div>", unsafe_allow_html=True
                    )
                    # Small delay to ensure output files are fully written
                    time.sleep(2)
                    with st.spinner("Running validation report (this may take a few minutes)..."):
                        try:
                            val_resp = requests.post(f"{API_URL}/api/validate/{job_id}", timeout=None)
                            if val_resp.status_code == 200:
                                st.session_state["validation_ready"] = True
                                st.rerun()
                            else:
                                st.session_state["validation_ready"] = "failed"
                                st.session_state["validation_error"] = val_resp.text
                                st.rerun()
                        except requests.Timeout:
                            st.session_state["validation_ready"] = "failed"
                            st.session_state["validation_error"] = "Request timed out"
                            st.rerun()
                        except Exception as e:
                            st.session_state["validation_ready"] = "failed"
                            st.session_state["validation_error"] = str(e)
                            st.rerun()
                else:
                    # Validation done — show all steps as complete
                    st.markdown(
                        "<div class='status-banner'>✅ <strong>Completed</strong> — All 11 steps finished successfully</div>",
                        unsafe_allow_html=True
                    )
                    with step_placeholder.container():
                        for i, s in enumerate(steps, 1):
                            st.markdown(f"<span class='step-done'>✓ {i}. {s}</span>", unsafe_allow_html=True)

                    try:
                        log_resp = requests.get(f"{API_URL}/api/log/{job_id}")
                        if log_resp.status_code == 200:
                            with st.expander("📜 Pipeline Log", expanded=False):
                                st.code(log_resp.json().get("log", "")[-5000:], language="text")
                    except:
                        pass

                    # ─── Results & Downloads ───
                    st.markdown("### 📦 Results")
                    col_dl1, col_dl2 = st.columns(2, gap="medium")

                    with col_dl1:
                        dl_resp = requests.get(f"{API_URL}/api/download/{job_id}")
                        if dl_resp.status_code == 200:
                            raw_name = os.path.splitext(status.get("file_name", "output"))[0]
                            short_name = raw_name[:40] if len(raw_name) > 40 else raw_name
                            st.download_button(
                                "📥 Download Output ZIP",
                                data=dl_resp.content,
                                file_name=f"{job_id}_{short_name}.zip",
                                mime="application/zip",
                                use_container_width=True,
                            )

                    with col_dl2:
                        if st.session_state.get("validation_ready") == True:
                            val_dl = requests.get(f"{API_URL}/api/download-validation/{job_id}")
                            if val_dl.status_code == 200:
                                raw_name = os.path.splitext(status.get("file_name", "output"))[0]
                                short_name = raw_name[:40] if len(raw_name) > 40 else raw_name
                                st.download_button(
                                    "📊 Download Validation Excel",
                                    data=val_dl.content,
                                    file_name=f"ValidationReport_{short_name}.xlsx",
                                    mime="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
                                    use_container_width=True,
                                )
                        else:
                            err_msg = st.session_state.get("validation_error", "Unknown error")
                            st.warning(f"⚠️ Validation failed: {err_msg}")
                            if st.button("🔄 Retry Validation", use_container_width=True):
                                st.session_state.pop("validation_ready", None)
                                st.session_state.pop("validation_error", None)
                                st.rerun()

                    st.markdown("")
                    if st.button("🔄 Process Another Document"):
                        del st.session_state["current_job"]
                        st.session_state.pop("job_status", None)
                        st.session_state.pop("validation_ready", None)
                        st.rerun()

            elif status["status"] == "failed":
                st.markdown(
                    f"<div class='status-banner status-banner-failed'>"
                    f"❌ <strong>Failed</strong> — {status.get('error', 'Unknown error')}"
                    f"</div>", unsafe_allow_html=True
                )
                try:
                    log_resp = requests.get(f"{API_URL}/api/log/{job_id}")
                    if log_resp.status_code == 200:
                        with st.expander("📜 Error Log", expanded=True):
                            st.code(log_resp.json().get("log", "")[-5000:], language="text")
                except:
                    pass

                if st.button("🔄 Try Again"):
                    del st.session_state["current_job"]
                    st.session_state.pop("job_status", None)
                    st.rerun()
